"""Builtin tool adapters: the ``fs`` family and the ``bash`` shell tool.

``fs__read`` (R2-S5), the R3-S3 static read trio ``fs__ls`` /
``fs__glob`` / ``fs__grep``, the R3-S4 mutation pair ``fs__write`` /
``fs__edit``, and the R3-S5 shell tool ``bash__run``. Adapters are
registered by the host (R2-S6) via
:meth:`opencode.tools.registry.ToolRegistry.register`; this package only
provides the implementations. R3-S6 (CORE-CONTRACTS §6 L287): the six fs
adapters accept an optional keyword-only ``roots`` constructor argument
(host config-declared extra roots, empty by default = the R2 single-root
semantics; the session working_dir always stays a root). P2-S6 (M2-git)
adds the read-only git pair ``git__status`` / ``git__diff`` (T-C1-053) and
P2-S7 (M2-git) the approved worktree trio ``git__worktree_add`` /
``git__worktree_list`` / ``git__worktree_remove`` (T-C1-055) -- same
``roots`` constructor shape. P6-S4 (T-C1-097, toolkit A) adds the
multi-file patch tool ``patch__apply`` and the stateless echo pair
``todo__write`` / ``question__ask``: same constant shape, and the three
ride both production host compositions (the CLI ``_drive`` tuple and
``serving._builtin_adapters``) beside the twelve, so every host face
carries 16 adapters while a tool-less App composition stays tool-less
(the app.py ``tools`` loop is host-param plumbing, not a registry).
P6-S5 (T-C1-098) adds the foreground subagent tool ``subagent__run``
(same constant shape, same dual-host ride): the one stateful builtin --
hosts bind the App service to the named instance after construction
(``SubagentRunAdapter.bind``), so host faces carry 17 adapters (16
base + the platform-gated PTY adapter). P7-S3 (T-C1-102) adds the
webfetch tool ``webfetch__fetch`` (same constant shape, same dual-host
ride): the one network builtin -- hosts bind the App permission policy
to the named instance after construction (``WebFetchAdapter.bind``),
so host faces carry 18 adapters (17 base + the platform-gated PTY
adapter). P7-S4 (T-C1-103) adds the websearch tool
``websearch__search`` (same constant shape, same dual-host ride):
the one consent-flow builtin -- hosts bind a WebSearchService (the
provider registry + KV selection seam) to the named instance after
construction (``WebSearchAdapter.bind``), so host faces carry 19
adapters (18 base + the platform-gated PTY adapter). T-C1-PT-012 adds
the read-only memory trio ``memory__search`` /
``memory__conversation_search`` / ``memory__read_scene`` (same
dual-host ride): the fail-soft builtins -- a host passes the gateway
client at construction and an unconfigured client is the expected
headless state (plan §4.2/§4.3), rendered as the structured
service-unavailable payload, never a raise -- so host faces carry 22
adapters (21 base + the platform-gated PTY adapter).
"""

